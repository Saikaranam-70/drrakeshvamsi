export function getLocalizedTreatments(locale: Locale): TreatmentDetail[] {
  if (locale === "te") {
    return treatmentsData.map((t) => {
      const teData = teluguTreatmentsMap[t.slug];
      if (!teData) return t;
      return {
        ...t,
        ...teData,
        overview: {
          ...t.overview,
          ...(teData.overview || {}),
        },
        recoveryInfo: {
          ...t.recoveryInfo,
          ...(teData.recoveryInfo || {}),
        },
      };
    });
  }

  if (locale === "hi") {
    return treatmentsData.map((t) => {
      const hiData = hindiTreatmentsMap[t.slug];
      if (!hiData) return t;
      return {
        ...t,
        ...hiData,
        overview: {
          ...t.overview,
          ...(hiData.overview || {}),
        },
        recoveryInfo: {
          ...t.recoveryInfo,
          ...(hiData.recoveryInfo || {}),
        },
      };
    });
  }

  return treatmentsData;
}

export function getLocalizedTreatment(slug: string, locale: Locale): TreatmentDetail | undefined {
  const all = getLocalizedTreatments(locale);
  return all.find((t) => t.slug === slug);
}
